"""Build the standalone SlimeBridge.exe (PyInstaller, one folder): Python, the launcher, BridgeHost, the extractor and
every dependency inside, plus the prebuilt plugins and SRMP Revival. Players unzip it and run SlimeBridge.exe.

    py -3.12 -m tools.release.build_exe [--plugins dist/SlimeBridge-v<VERSION>/plugins]

Run tools.release.make_release first (it builds the plugins and stages them). Output:
dist/SlimeBridge-v<VERSION>-win64-standalone.zip (SlimeBridge/SlimeBridge.exe) on Windows, or
dist/SlimeBridge-v<VERSION>-linux-x64-standalone.tar.gz (SlimeBridge/SlimeBridge) on Linux. The Linux build runs on
GitHub Actions (.github/workflows/linux-release.yml) each time a release is published, with the plugins taken from
that release's source zip.

Everything SlimeBridge writes at run time (settings, extracted content) goes to the Lab folder inside the program folder,
so the folder must stay somewhere the player can write (not Program Files). Starlight (Slime Rancher 2 online) is not
inside: its license forbids redistribution; the launcher downloads it from its official release when online is set up.
"""
import argparse
import os
import re
import shutil
import subprocess
import sys
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DIST = ROOT / 'dist'
WORK = ROOT / 'build' / 'pyinstaller'
DATA_DIRS = ('apps', 'bridge', 'tools/SlimeBridge-AssetConverter', 'tools/lab', 'tools/content', 'fixtures')
DATA_SKIP = re.compile(r'(__pycache__|\.pyc$|/bin/|/obj/|/\.venv/|/output[^/]*/|/work/)')
WINDOWS = sys.platform == 'win32'
PLATFORM = 'win64' if WINDOWS else 'linux-x64'
COLLECT_ALL = ('webview', 'UnityPy', 'TypeTreeGeneratorAPI', 'fmod_toolkit', 'texture2ddecoder', 'etcpak', 'astc_encoder',
               'pygltflib', 'dnfile', 'lz4', 'brotli', 'archspec', 'tpk_ar') + (('clr_loader', 'pythonnet') if WINDOWS else ())
TOP_FILES = ('README.md', 'LICENSE', 'THIRD_PARTY_NOTICES.md', 'LICENSES.md', 'CHANGELOG.md', 'VERSION')


SPEC = """# Generated by tools/release/build_exe.py
from PyInstaller.utils.hooks import collect_all

datas, binaries, hiddenimports = {datas}, [], {hidden}
for package in {collect}:
    d, b, h = collect_all(package)
    datas += d; binaries += b; hiddenimports += h

a = Analysis([{entry}], pathex={paths}, binaries=binaries, datas=datas, hiddenimports=hiddenimports,
             hookspath=[], runtime_hooks=[], excludes=['tkinter', 'PySide6', 'PyQt5', 'PyQt6', 'matplotlib', 'pytest'],
             noarchive=False)
pyz = PYZ(a.pure)
exe = EXE(pyz, a.scripts, [], exclude_binaries=True, name='SlimeBridge', debug=False, strip=False, upx=False,
          console={console})
coll = COLLECT(exe, a.binaries, a.datas, strip=False, upx=False, name='SlimeBridge')
"""


def die(message):
    print('ERROR: ' + message)
    sys.exit(1)


def data_args(plugins: Path):
    sep = os.pathsep
    args = []
    for folder in DATA_DIRS:
        base = ROOT / folder
        for path in sorted(base.rglob('*')):
            rel = path.relative_to(ROOT).as_posix()
            if not path.is_file() or DATA_SKIP.search('/' + rel):
                continue
            # Python files stay as files too: the launcher locates the extractor by its sbconv/__init__.py, and the
            # frozen modules themselves come from the PYZ archive (hidden imports below).
            args += ['--add-data', f'{path}{sep}{Path(rel).parent.as_posix()}']
    for path in sorted(plugins.rglob('*')):
        if path.is_file():
            rel = Path('plugins') / path.relative_to(plugins)
            args += ['--add-data', f'{path}{sep}{rel.parent.as_posix()}']
    for name in ('docs/SPECIES_ADAPTER.md', 'docs/runtime-scenarios.json', 'Lab/README.md', 'VERSION'):
        if (ROOT / name).is_file():
            args += ['--add-data', f'{ROOT / name}{sep}{Path(name).parent.as_posix() or "."}']
    return args


def hidden_imports():
    names = set()
    for package in ('apps', 'bridge', 'tools/lab', 'tools/content', 'tools/release'):
        for path in (ROOT / package).rglob('*.py'):
            if '__pycache__' in path.parts:
                continue
            module = path.relative_to(ROOT).with_suffix('').as_posix().replace('/', '.')
            names.add(module[:-len('.__init__')] if module.endswith('.__init__') else module)
    converter = ROOT / 'tools' / 'SlimeBridge-AssetConverter'
    for path in (converter / 'sbconv').rglob('*.py'):
        module = path.relative_to(converter).with_suffix('').as_posix().replace('/', '.')
        names.add(module[:-len('.__init__')] if module.endswith('.__init__') else module)
    args = []
    for name in sorted(names):
        args += ['--hidden-import', name]
    return args


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    version = (ROOT / 'VERSION').read_text(encoding='utf-8').strip()
    parser.add_argument('--plugins', default=str(DIST / f'SlimeBridge-v{version}' / 'plugins'))
    parser.add_argument('--console', action='store_true', help='keep a console window (debugging)')
    args = parser.parse_args()
    plugins = Path(args.plugins)
    for required in ('SR1/SlimeBridge.SR1.dll', 'SR2/SlimeBridge.SR2.dll'):
        if not (plugins / required).is_file():
            die(f'{plugins / required} missing: run tools.release.make_release first')
    try:
        import PyInstaller  # noqa: F401
    except ImportError:
        die('PyInstaller is required: python -m pip install pyinstaller')

    out = WORK / 'dist'
    shutil.rmtree(WORK, ignore_errors=True)
    WORK.mkdir(parents=True)
    datas = [(a.split(os.pathsep)[0], a.split(os.pathsep)[1]) for a in data_args(plugins)[1::2]]
    hidden = hidden_imports()[1::2]
    spec = WORK / 'SlimeBridge.spec'
    spec.write_text(SPEC.format(entry=repr(str(ROOT / 'apps' / 'launcher' / 'exe_main.py')),
                                paths=repr([str(ROOT), str(ROOT / 'tools' / 'SlimeBridge-AssetConverter')]),
                                datas=repr(datas), hidden=repr(hidden), collect=repr(list(COLLECT_ALL)),
                                console=repr(bool(args.console))), encoding='utf-8')
    print(f'== PyInstaller ({len(datas)} data files, {len(hidden)} modules)')
    proc = subprocess.run([sys.executable, '-m', 'PyInstaller', str(spec), '--noconfirm', '--clean',
                           '--distpath', str(out), '--workpath', str(WORK / 'work')], cwd=ROOT)
    if proc.returncode != 0:
        die('PyInstaller failed')
    app = out / 'SlimeBridge'
    for name in TOP_FILES:
        if (ROOT / name).is_file():
            shutil.copy2(ROOT / name, app / name)
    if WINDOWS:
        archive = DIST / f'SlimeBridge-v{version}-win64-standalone.zip'
        if archive.exists():
            archive.unlink()
        with zipfile.ZipFile(archive, 'w', zipfile.ZIP_DEFLATED, compresslevel=6) as zf:
            for path in sorted(app.rglob('*')):
                if path.is_file():
                    zf.write(path, f'SlimeBridge/{path.relative_to(app).as_posix()}')
    else:
        import tarfile
        archive = DIST / f'SlimeBridge-v{version}-linux-x64-standalone.tar.gz'
        if archive.exists():
            archive.unlink()
        with tarfile.open(archive, 'w:gz') as tf:
            tf.add(app, arcname='SlimeBridge')
    print(f'OK  {app / ("SlimeBridge.exe" if WINDOWS else "SlimeBridge")}\n    {archive} ({archive.stat().st_size / 1e6:.1f} MB)')


if __name__ == '__main__':
    main()
